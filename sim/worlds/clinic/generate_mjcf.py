#!/usr/bin/env python3
"""Clinic world as MuJoCo MJCF (side lane H, task 003), next to the SDF writer.

    python3 sim/worlds/clinic/generate_mjcf.py sim/worlds/clinic/layout.yaml --out DIR

Writes <out>/clinic.xml and <out>/clinic_labels.json. The MJCF is a translation of the SDF that generate.py builds
from the same layout.yaml (in memory; generate.py and its outputs are untouched), so parts_for, COLOURS, the wall
segments, doorways, lintels, floors, ceiling and lamps are generate.py's own, with the same 4-decimal numbers
Gazebo loads. Geometry and colour cannot drift between the two worlds.

One static MuJoCo body per SDF model, named after it (objects: the layout id; structure: structure_*), one geom per
SDF visual (collision on, as the SDF gives every visual an identical collision). Labels: clinic_labels.json maps
body name -> label, from each model's gz Label plugin (objects 1..199 = truth.json `label`, structure 240..243).
A consumer turns MuJoCo segmentation into truth labels with body id -> body name -> label; any body not in the map
(the robot, the world body, background) is label 0, which the SDF world also leaves unlabelled.
Deterministic: same layout.yaml -> byte-identical output.
"""
from __future__ import annotations

import argparse
import json
import math
import xml.etree.ElementTree as ET
from pathlib import Path

from generate import fs, generate

LABEL_PLUGIN = "gz::sim::systems::Label"


def _geom(name: str, visual: ET.Element) -> str:
    x, y, z = (float(v) for v in visual.findtext("pose").split()[:3])
    g = visual.find("geometry")[0]
    if g.tag == "box":
        kind, size = "box", [float(v) / 2 for v in g.findtext("size").split()]
    elif g.tag == "cylinder":
        kind, size = "cylinder", [float(g.findtext("radius")), float(g.findtext("length")) / 2]
    else:
        kind, size = "sphere", [float(g.findtext("radius"))]
    rgba = visual.find("material").findtext("diffuse")
    return f'      <geom name="{name}" type="{kind}" size="{fs(*size)}" pos="{fs(x, y, z)}" rgba="{rgba}"/>'


def _quat(yaw: float) -> str:
    """Yaw quaternion at 9 decimals: fs()'s 4 would move the SDF's yaw by up to ~1e-4 rad."""
    return " ".join(f"{v:.9f}" for v in (math.cos(yaw / 2), 0.0, 0.0, math.sin(yaw / 2)))


def _light(el: ET.Element) -> str:
    x, y, z = (float(v) for v in el.findtext("pose").split()[:3])
    att = el.find("attenuation")
    a = fs(*(float(att.findtext(k)) for k in ("constant", "linear", "quadratic")))
    diffuse = " ".join(el.findtext("diffuse").split()[:3])
    specular = " ".join(el.findtext("specular").split()[:3])
    return (f'    <light name="{el.get("name")}" type="point" pos="{fs(x, y, z)}" diffuse="{diffuse}" '
            f'specular="{specular}" attenuation="{a}" range="{att.findtext("range")}" castshadow="false"/>')


def generate_mjcf(layout_path: Path, blocked: str | None = None, mocap: frozenset[str] = frozenset()) -> tuple[str, str]:
    """Return (clinic.xml text, clinic_labels.json text) for a layout file. blocked: generate()'s blocker room. mocap:
    body (= SDF model) names written as mocap bodies (task 012: spec objects placed per run by mocap pose)."""
    sdf, truth_text = generate(layout_path, blocked=blocked)
    truth = json.loads(truth_text)
    world = ET.fromstring(sdf).find("world")
    lines = ['<?xml version="1.0"?>',
             f"<!-- GENERATED by sim/worlds/clinic/generate_mjcf.py from layout.yaml (sha256 {truth['layout_sha256']})"
             " via generate.py's SDF. Do not edit. -->",
             f'<mujoco model="{truth["world"]}">',
             "  <worldbody>"]
    lines += [_light(el) for el in world.findall("light")]
    labels: dict[str, int] = {}
    for model in world.findall("model"):
        name = model.get("name")
        x, y, z, _, _, yaw = (float(v) for v in model.findtext("pose").split())
        labels[name] = int(next(p for p in model.iter("plugin") if p.get("name") == LABEL_PLUGIN).findtext("label"))
        mc = ' mocap="true"' if name in mocap else ""
        lines.append(f'    <body name="{name}"{mc} pos="{fs(x, y, z)}" quat="{_quat(yaw)}">')
        lines += [_geom(f"{name}/{v.get('name')}", v) for v in model.find("link").findall("visual")]
        lines.append("    </body>")
    lines += ["  </worldbody>", "</mujoco>", ""]
    meta = {"layout_sha256": truth["layout_sha256"], "body_labels": labels,
            "structure_labels": truth["structure_labels"], "unlabelled": 0}
    return "\n".join(lines), json.dumps(meta, indent=1, sort_keys=True) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("layout", type=Path)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    xml, labels = generate_mjcf(a.layout)
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "clinic.xml").write_text(xml)
    (a.out / "clinic_labels.json").write_text(labels)
    print(f"wrote {a.out / 'clinic.xml'} and {a.out / 'clinic_labels.json'}")


if __name__ == "__main__":
    main()
